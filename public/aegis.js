// Built with AEGIS V2 — renders ONLY real records served from registry files.
// No counts are hardcoded here; missing data renders as not-run / none recorded.
const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const host = document.getElementById("aegis-body");
async function getJSON(path) { const r = await fetch(path); if (!r.ok) throw new Error(path); return r.json(); }

function gateSection(report) {
  const gates = report.gates || [];
  return `<section class="card"><h2>Blueprint gate results</h2>
  <p>Blueprint: <code>${esc(report.blueprint || "—")}</code> · Components: ${esc(report.componentCount ?? "—")} · Valid: ${esc(String(report.valid ?? "—"))}<br>
  <span class="muted">Source: <code>registry/gate-report.json</code> (written by <code>tools/aegis/gates.mjs run</code>). Unrun gates stay <em>not-run</em>.</span></p>
  <table><thead><tr><th>Gate</th><th>Name</th><th>Status</th></tr></thead><tbody>${gates.map((g) => `<tr><td>${esc(g.id)}</td><td>${esc(g.name)}</td><td>${esc(g.status)}</td></tr>`).join("") || '<tr><td colspan="3">No gates recorded.</td></tr>'}</tbody></table></section>`;
}

function registrySection(registry) {
  const comps = registry.components || [];
  if (!comps.length) return `<section class="card"><h2>Verified components &amp; reuse</h2><p>No verified components recorded in <code>registry/components.json</code> yet — nothing is claimed as reused.</p></section>`;
  return `<section class="card"><h2>Verified components &amp; reuse</h2>
  <p class="muted">Source: <code>registry/components.json</code> (written only by <code>tools/aegis/gates.mjs accept</code> after provenance + executed-test checks).</p>
  ${comps.map((c) => `<h3><code>${esc(c.id)}@${esc(c.version)}</code> — ${esc(c.status)}</h3>
  <table><tbody>
  <tr><th>Contract hash (sha256)</th><td><code>${esc(c.contractHash)}</code></td></tr>
  <tr><th>Source hash (sha256)</th><td><code>${esc(c.sourceHash)}</code></td></tr>
  <tr><th>Implementation / provenance</th><td><code>${esc(c.provenance?.source || "—")}</code></td></tr>
  <tr><th>Dependencies</th><td>${(c.dependencies || []).map(esc).join(", ") || "none"}</td></tr>
  <tr><th>Executed test evidence</th><td>${(c.testEvidence || []).map((t) => `${esc(t.test)} — passed:${esc(String(t.passed))} exitCode:${esc(String(t.exitCode))}`).join("; ") || "none recorded"}</td></tr>
  <tr><th>Limitations</th><td>${(c.limitations || []).map(esc).join("; ") || "none recorded"}</td></tr>
  </tbody></table>
  ${c.id === "safety-filter" ? `<div class="notice" role="status"><strong>Real reuse in the running app:</strong> Professor D imports this verified component — <code>import { checkTopic } from "/src/safety-filter.js"</code> in <code>public/app.js</code> (served from <code>src/safety-filter.js</code>, whose sha256 is the source hash above). Re-resolve it with <code>node tools/aegis/registry.mjs resolve safety-filter@1.0.0</code> → <code>reused:true</code>; a version mismatch fails instead of silently upgrading.</div>` : ""}`).join("")}</section>`;
}

function testSection(report) {
  if (!report || report.status === "not-run" || report.tests === undefined) {
    return `<section class="card"><h2>Test report</h2><p>Test report not-run yet. Generate the real file with <code>npm run test:report</code> (it executes the test suite and records its actual counts in <code>registry/test-report.json</code>).</p></section>`;
  }
  return `<section class="card"><h2>Test report</h2>
  <p class="muted">Source: <code>registry/test-report.json</code> — generated by executing the suite, never typed by hand.</p>
  <table><tbody>
  <tr><th>Command</th><td><code>${esc(report.command)}</code></td></tr>
  <tr><th>Generated</th><td>${esc(report.generatedAt)}</td></tr>
  <tr><th>Tests / passed / failed / skipped</th><td>${esc(report.tests)} / ${esc(report.pass)} / ${esc(report.fail)} / ${esc(report.skipped)}</td></tr>
  <tr><th>Exit code</th><td>${esc(report.exitCode)}</td></tr>
  <tr><th>Status</th><td>${esc(report.status)}</td></tr>
  </tbody></table></section>`;
}

function eventsSection(events) {
  const list = Array.isArray(events) ? events : [];
  return `<section class="card"><h2>Gate events</h2>
  <p class="muted">Source: <code>registry/gate-events.jsonl</code> (append-only log written by the gate tools).</p>
  ${list.length ? `<table><thead><tr><th>Time</th><th>Type</th><th>Detail</th></tr></thead><tbody>${list.map((e) => `<tr><td>${esc(e.ts || "")}</td><td>${esc(e.type || "")}</td><td>${esc(e.blueprint || e.staged || e.id || "")} ${e.valid !== undefined ? `valid:${esc(String(e.valid))}` : ""} ${e.accepted !== undefined ? `accepted:${esc(String(e.accepted))}` : ""}</td></tr>`).join("")}</tbody></table>` : "<p>No gate events recorded.</p>"}</section>`;
}

function invalidSection(inv) {
  if (!inv || inv.valid === null || inv.valid === undefined) {
    return `<section class="card"><h2>Intentionally invalid blueprint — rejection proof</h2><p>${esc(inv?.note || "Invalid-blueprint fixture unavailable; nothing is claimed.")}</p></section>`;
  }
  return `<section class="card"><h2>Intentionally invalid blueprint — rejection proof</h2>
  <p>File: <code>${esc(inv.file)}</code> · Validator verdict: <strong>valid: ${esc(String(inv.valid))}</strong> (rejected — never partially built).<br>
  <span class="muted">Computed live by the executable validator (<code>tools/aegis/lib.mjs validateBlueprint</code>). Reproduce: <code>${esc(inv.reproduce)}</code> (exit 1).</span></p>
  <table><thead><tr><th>Path</th><th>Rule</th><th>Message</th></tr></thead><tbody>${(inv.errors || []).map((e) => `<tr><td><code>${esc(e.path)}</code></td><td>${esc(e.rule)}</td><td>${esc(e.message)}</td></tr>`).join("") || '<tr><td colspan="3">No errors recorded.</td></tr>'}</tbody></table></section>`;
}

(async () => {
  try {
    const [report, registry, tests, events, invalid] = await Promise.all([
      getJSON("/api/aegis/report"), getJSON("/api/aegis/registry"), getJSON("/api/aegis/tests"), getJSON("/api/aegis/events"), getJSON("/api/aegis/invalid"),
    ]);
    host.innerHTML = [gateSection(report), registrySection(registry), testSection(tests), invalidSection(invalid), eventsSection(events)].join("");
  } catch {
    host.innerHTML = `<div class="notice">AEGIS records unavailable right now. Run the server with <code>npm start</code> and the gate script, then reload. Nothing has been marked as passed.</div>`;
  }
})();
